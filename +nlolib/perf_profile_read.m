function snapshot = perf_profile_read()
%PERF_PROFILE_READ Read the runtime performance counters.
%   snapshot = nlolib.perf_profile_read()
%
%   Returns a struct with the fields of the C nlo_perf_profile_snapshot:
%     dispersion_ms, nonlinear_ms, dispersion_calls, nonlinear_calls,
%     gpu_dispatch_count, gpu_copy_count, gpu_device_copy_count,
%     gpu_device_copy_bytes, gpu_host_transfer_copy_count,
%     gpu_host_transfer_copy_bytes, gpu_memory_pass_count,
%     gpu_memory_pass_bytes, gpu_upload_count, gpu_download_count,
%     gpu_upload_bytes, gpu_download_bytes, operator_jit_programs,
%     operator_jit_fallbacks
%
%   See also NLOLIB.PERF_PROFILE_SET_ENABLED, NLOLIB.PERF_PROFILE_RESET.
require_function('nlolib_perf_profile_read');
snapshotRaw = zeroed_libstruct('nlo_perf_profile_snapshot', ...
    {'dispersion_ms', 'nonlinear_ms', ...
     'dispersion_calls', 'nonlinear_calls', ...
     'gpu_dispatch_count', 'gpu_copy_count', ...
     'gpu_device_copy_count', 'gpu_device_copy_bytes', ...
     'gpu_host_transfer_copy_count', 'gpu_host_transfer_copy_bytes', ...
     'gpu_memory_pass_count', 'gpu_memory_pass_bytes', ...
     'gpu_upload_count', 'gpu_download_count', ...
     'gpu_upload_bytes', 'gpu_download_bytes', ...
     'operator_jit_programs', 'operator_jit_fallbacks'});
check_status(calllib('nlolib', 'nlolib_perf_profile_read', snapshotRaw), ...
             'nlolib_perf_profile_read');
snapshot = struct(snapshotRaw);
end
